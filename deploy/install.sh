#!/usr/bin/env bash
# Foxalora Mail installer.
# Usage:
#   ./deploy/install.sh webmail.yourdomain.com --letsencrypt you@yourdomain.com   # real certificate
#   ./deploy/install.sh webmail.yourdomain.com --self-signed                      # testing only
#   ./deploy/install.sh webmail.yourdomain.com                                    # your own deploy/certs/*.pem
#
# Needs: a Linux server with Docker and Docker Compose v2, ports 80 and 443 open, and the domain's
# DNS A record pointing at this server (for --letsencrypt).
# What it does: creates deploy/.env with fresh random secrets, gets a TLS certificate, builds and
# starts the stack (Nginx, API, PostgreSQL, Valkey), runs migrations and creates the first tenant.
# Safe to run again: secrets, certificates and data are kept.
set -euo pipefail
START=$(date +%s)

DOMAIN="${1:-}"
CERT_MODE="own"
LE_EMAIL=""
case "${2:-}" in
  --self-signed) CERT_MODE="self-signed" ;;
  --letsencrypt) CERT_MODE="letsencrypt"; LE_EMAIL="${3:-}" ;;
  "") ;;
  *) echo "Unknown option: $2" >&2; exit 2 ;;
esac

usage() { sed -n '3,6p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 1; }
[ -n "$DOMAIN" ] || usage
# A plain host name only: letters, digits, dots and hyphens (it ends up in Nginx config and URLs).
[[ "$DOMAIN" =~ ^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?)+$ ]] \
  || { echo "Not a valid host name: $DOMAIN" >&2; exit 1; }
if [ "$CERT_MODE" = letsencrypt ] && [[ ! "$LE_EMAIL" =~ ^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$ ]]; then
  echo "--letsencrypt needs an email address for expiry notices: --letsencrypt you@yourdomain.com" >&2; exit 1
fi

cd "$(dirname "$0")"
step() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
need() { command -v "$1" >/dev/null 2>&1 || { echo "Missing requirement: $1" >&2; exit 1; }; }
need docker
need openssl
docker info >/dev/null 2>&1 || { echo "Docker is not running, or this user may not use it (try sudo)." >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "Docker Compose v2 is required (the 'docker compose' plugin)." >&2; exit 1; }
COMPOSE=(docker compose -f docker-compose.prod.yml --env-file .env)

step "Secrets"
if [ ! -f .env ]; then
  (
    umask 077
    cat > .env <<EOF
# Generated by install.sh on $(date -u +%Y-%m-%d). Keep private and back it up: losing
# VAULT_KEYS only signs users out, losing the database passwords locks you out of your data.
DOMAIN=${DOMAIN}
POSTGRES_PASSWORD=$(openssl rand -hex 24)
APP_DB_PASSWORD=$(openssl rand -hex 24)
VALKEY_PASSWORD=$(openssl rand -hex 24)
VAULT_KEYS=k1:$(openssl rand -base64 32)
SESSION_IDLE_MINUTES=30
SESSION_MAX_HOURS=12
EOF
  )
  echo "Created deploy/.env with new random secrets."
else
  CURRENT=$(sed -n 's/^DOMAIN=//p' .env)
  if [ "$CURRENT" != "$DOMAIN" ]; then
    echo "deploy/.env is for $CURRENT, not $DOMAIN. Edit DOMAIN in deploy/.env (and replace deploy/certs) to change it." >&2
    exit 1
  fi
  echo "deploy/.env already exists; keeping it."
fi

step "TLS certificate"
mkdir -p certs acme
if [ -s certs/fullchain.pem ] && [ -s certs/privkey.pem ]; then
  echo "Using the existing certificate in deploy/certs/."
elif [ "$CERT_MODE" = self-signed ]; then
  openssl req -x509 -nodes -newkey rsa:2048 -days 30 \
    -keyout certs/privkey.pem -out certs/fullchain.pem \
    -subj "/CN=${DOMAIN}" -addext "subjectAltName=DNS:${DOMAIN}" >/dev/null 2>&1
  chmod 600 certs/privkey.pem
  echo "Created a 30-day self-signed certificate. Browsers will warn. Testing only."
elif [ "$CERT_MODE" = letsencrypt ]; then
  # Port 80 must be free for the one-off challenge; the web container is not running yet on a first install.
  "${COMPOSE[@]}" stop web >/dev/null 2>&1 || true
  docker run --rm -p 80:80 -v "$PWD/letsencrypt:/etc/letsencrypt" certbot/certbot:v5.9.0 \
    certonly --standalone --non-interactive --agree-tos -m "$LE_EMAIL" -d "$DOMAIN"
  cp -L "letsencrypt/live/$DOMAIN/fullchain.pem" certs/fullchain.pem
  (umask 077 && cp -L "letsencrypt/live/$DOMAIN/privkey.pem" certs/privkey.pem)
  echo "Let's Encrypt certificate installed. Renew it with deploy/renew-cert.sh (see the docs for a cron line)."
else
  echo "No certificate in deploy/certs/ (fullchain.pem and privkey.pem)." >&2
  echo "Re-run with --letsencrypt you@yourdomain.com, or --self-signed for a quick test." >&2
  exit 1
fi

step "Build and start (the first build takes a few minutes)"
"${COMPOSE[@]}" up -d --build

printf 'Waiting for the API'
for _ in $(seq 1 60); do
  if [ "$(docker inspect -f '{{.State.Health.Status}}' "$("${COMPOSE[@]}" ps -q api)" 2>/dev/null)" = healthy ]; then
    echo " ok"; break
  fi
  printf '.'; sleep 2
done
[ "$(docker inspect -f '{{.State.Health.Status}}' "$("${COMPOSE[@]}" ps -q api)" 2>/dev/null)" = healthy ] \
  || { echo " not healthy. Check: docker compose -f deploy/docker-compose.prod.yml logs api migrate" >&2; exit 1; }

step "Tenant"
TENANTS=$("${COMPOSE[@]}" --profile tools run --rm -T cli tenant:list)
if [ -z "$TENANTS" ]; then
  TENANT_ID=$("${COMPOSE[@]}" --profile tools run --rm -T cli tenant:create "Default" | tail -1)
  echo "Created tenant $TENANT_ID"
else
  TENANT_ID=$(echo "$TENANTS" | head -1 | awk '{print $1}')
  echo "Tenant exists: $TENANT_ID"
fi

MINUTES=$(( ($(date +%s) - START + 59) / 60 ))
cat <<EOF

Foxalora is running at https://${DOMAIN}   (install took about ${MINUTES} min)

Next: tell Foxalora which mail server serves each email domain, for example
  ./deploy/cli.sh server:add ${TENANT_ID} main --imap mail.example.com:993:tls --smtp mail.example.com:465:tls
  ./deploy/cli.sh domain:map ${TENANT_ID} example.com main
  ./deploy/cli.sh server:list ${TENANT_ID}
(Gmail: imap.gmail.com:993:tls and smtp.gmail.com:465:tls with --saves-sent; users sign in with an app password.)

Status : docker compose -f deploy/docker-compose.prod.yml ps
Logs   : docker compose -f deploy/docker-compose.prod.yml logs -f api
Stop   : docker compose -f deploy/docker-compose.prod.yml down
Back up deploy/.env and the database volume.
EOF
