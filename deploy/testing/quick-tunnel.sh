#!/usr/bin/env bash
# Stopgap: runs the Foxalora production stack on THIS machine with plain docker (no Compose
# needed) and publishes it through a free Cloudflare quick tunnel (https://<random>.trycloudflare.com),
# behind the password gate. For short tests until a real server exists (docs/runbooks/install.md).
#
#   ./deploy/testing/quick-tunnel.sh up       start or restart (prints the public link)
#   ./deploy/testing/quick-tunnel.sh cli ...  operator CLI (e.g. server:list <tenantId>)
#   ./deploy/testing/quick-tunnel.sh down     stop everything (database kept)
#
# The quick-tunnel link changes every time the tunnel restarts; this machine must stay on.
# Password gate: on by default; FOXALORA_GATE=0 in deploy/.env turns it off.
# Same images, settings and hardening as docker-compose.prod.yml; secrets in deploy/.env.
set -euo pipefail
cd "$(dirname "$0")/.."     # deploy/
ROOT=$(cd .. && pwd)
N=foxalora-quick
P=fq
CLOUDFLARED=cloudflare/cloudflared:2026.10.7
env_get() { sed -n "s/^$1=//p" .env | tail -1; }

down() {
  docker rm -f ${P}-cloudflared ${P}-web ${P}-api ${P}-valkey ${P}-postgres >/dev/null 2>&1 || true
  echo "Stopped. Database kept in the volume foxalora-quick-pgdata."
}

cli() {
  docker run --rm --network $N --read-only --cap-drop ALL --security-opt no-new-privileges:true \
    -e NODE_ENV=production \
    -e DATABASE_OWNER_URL="postgres://foxalora:$(env_get POSTGRES_PASSWORD)@postgres:5432/foxalora" \
    -e DATABASE_URL="postgres://foxalora_app:$(env_get APP_DB_PASSWORD)@postgres:5432/foxalora" \
    --entrypoint node foxalora-api:local dist/cli.js "$@"
}

up() {
  command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }
  docker image inspect foxalora-api:local foxalora-web:local >/dev/null 2>&1 || {
    echo "Building images (a few minutes)..."
    docker build -q -f "$ROOT/backend/Dockerfile" -t foxalora-api:local "$ROOT" >/dev/null
    docker build -q -f "$ROOT/frontend/Dockerfile" -t foxalora-web:local "$ROOT" >/dev/null
  }
  if [ ! -f .env ]; then
    (umask 077; cat > .env <<EOF
# Generated by quick-tunnel.sh on $(date -u +%Y-%m-%d). Keep private.
DOMAIN=pending.trycloudflare.com
POSTGRES_PASSWORD=$(openssl rand -hex 24)
APP_DB_PASSWORD=$(openssl rand -hex 24)
VALKEY_PASSWORD=$(openssl rand -hex 24)
VAULT_KEYS=k1:$(openssl rand -base64 32)
SESSION_IDLE_MINUTES=30
SESSION_MAX_HOURS=12
EOF
    )
  fi
  # Certificate for the hop tunnel -> Nginx (the tunnel does not verify it; visitors see Cloudflare's).
  mkdir -p certs/quick
  if [ ! -s certs/quick/fullchain.pem ]; then
    openssl req -x509 -nodes -newkey rsa:2048 -days 825 -keyout certs/quick/privkey.pem -out certs/quick/fullchain.pem \
      -subj "/CN=web" -addext "subjectAltName=DNS:web" >/dev/null 2>&1
    chmod 644 certs/quick/privkey.pem # read by the nginx worker; used only on the local Docker network
  fi
  GATE_ARGS=()
  if grep -qx 'FOXALORA_GATE=0' .env; then
    GATE_LINE="Password gate: OFF (anyone with the link reaches the login page)"
  else
    [ -s testing/gate/htpasswd ] || GATE_LINE=$(./testing/gate.sh set tester | tail -1)
    GATE_ARGS=(-v "$PWD/testing/nginx/gate.conf:/etc/nginx/foxalora.d/gate.conf:ro" -v "$PWD/testing/gate:/etc/nginx/foxalora-gate:ro")
  fi

  docker network inspect $N >/dev/null 2>&1 || docker network create $N >/dev/null
  docker rm -f ${P}-cloudflared ${P}-web ${P}-api >/dev/null 2>&1 || true

  docker inspect ${P}-postgres >/dev/null 2>&1 || docker run -d --name ${P}-postgres --network $N --network-alias postgres \
    --restart unless-stopped -e POSTGRES_DB=foxalora -e POSTGRES_USER=foxalora \
    -e POSTGRES_PASSWORD="$(env_get POSTGRES_PASSWORD)" -e FOXALORA_APP_DB_PASSWORD="$(env_get APP_DB_PASSWORD)" \
    -v "$PWD/db/01-app-role.sh:/docker-entrypoint-initdb.d/01-app-role.sh:ro" \
    -v foxalora-quick-pgdata:/var/lib/postgresql postgres:18.6-alpine >/dev/null
  docker start ${P}-postgres >/dev/null
  docker inspect ${P}-valkey >/dev/null 2>&1 || docker run -d --name ${P}-valkey --network $N --network-alias valkey \
    --restart unless-stopped valkey/valkey:9.0.7-alpine \
    valkey-server --requirepass "$(env_get VALKEY_PASSWORD)" --save "" --appendonly no >/dev/null
  docker start ${P}-valkey >/dev/null

  printf 'Waiting for PostgreSQL'
  for _ in $(seq 1 60); do docker exec ${P}-postgres pg_isready -h 127.0.0.1 -U foxalora -d foxalora >/dev/null 2>&1 && break; printf '.'; sleep 1; done
  echo; sleep 2
  docker run --rm --network $N --read-only --cap-drop ALL --security-opt no-new-privileges:true -e NODE_ENV=production \
    -e DATABASE_OWNER_URL="postgres://foxalora:$(env_get POSTGRES_PASSWORD)@postgres:5432/foxalora" \
    foxalora-api:local node dist/cli.js migrate

  echo "Starting the tunnel..."
  docker run -d --name ${P}-cloudflared --network $N --restart unless-stopped $CLOUDFLARED \
    tunnel --no-autoupdate --url https://web:443 --no-tls-verify >/dev/null
  URL=""
  for _ in $(seq 1 60); do
    URL=$(docker logs ${P}-cloudflared 2>&1 | grep -oE 'https://[a-z0-9-]+\.trycloudflare\.com' | head -1 || true)
    [ -n "$URL" ] && break; sleep 1
  done
  [ -n "$URL" ] || { echo "The tunnel did not report a link. Check: docker logs ${P}-cloudflared" >&2; exit 1; }
  DOMAIN=${URL#https://}
  sed -i "s/^DOMAIN=.*/DOMAIN=${DOMAIN}/" .env

  docker run -d --name ${P}-api --network $N --network-alias api --restart unless-stopped --read-only --tmpfs /tmp \
    --cap-drop ALL --security-opt no-new-privileges:true -e NODE_ENV=production -e PORT=3000 \
    -e DATABASE_URL="postgres://foxalora_app:$(env_get APP_DB_PASSWORD)@postgres:5432/foxalora" \
    -e VALKEY_URL="redis://:$(env_get VALKEY_PASSWORD)@valkey:6379" \
    -e FOXALORA_VAULT_KEYS="$(env_get VAULT_KEYS)" -e ALLOWED_HOSTS="$DOMAIN" \
    -e SESSION_IDLE_MINUTES="$(env_get SESSION_IDLE_MINUTES)" -e SESSION_MAX_HOURS="$(env_get SESSION_MAX_HOURS)" \
    foxalora-api:local >/dev/null
  docker run -d --name ${P}-web --network $N --network-alias web --restart unless-stopped -e DOMAIN="$DOMAIN" \
    -v "$PWD/certs/quick:/certs:ro" \
    -v "$PWD/testing/nginx/tunnel.conf:/etc/nginx/foxalora.d/tunnel.conf:ro" \
    "${GATE_ARGS[@]}" foxalora-web:local >/dev/null

  # Tenant and Gmail mapping (testers sign in with Gmail test accounts and app passwords).
  TENANT_ID=$(cli tenant:list | head -1 | awk '{print $1}')
  [ -n "$TENANT_ID" ] || TENANT_ID=$(cli tenant:create Default | tail -1)
  if ! cli server:list "$TENANT_ID" | grep -q '^gmail:'; then
    cli server:add "$TENANT_ID" gmail --imap imap.gmail.com:993:tls --smtp smtp.gmail.com:465:tls --saves-sent >/dev/null
    cli domain:map "$TENANT_ID" gmail.com gmail >/dev/null
  fi

  printf 'Waiting for the API'
  for _ in $(seq 1 30); do
    [ "$(docker inspect -f '{{.State.Health.Status}}' ${P}-api)" = healthy ] && break; printf '.'; sleep 2
  done
  echo
  cat <<EOF

Foxalora is online:  $URL
  ${GATE_LINE:-Gate logins: $(cut -d: -f1 testing/gate/htpasswd | paste -sd, -)  (new password: ./deploy/testing/gate.sh set tester)}
  Testers sign in with a Gmail test account and its app password (see docs/runbooks/testing.md).
  Tenant: $TENANT_ID   (mail servers: ./deploy/testing/quick-tunnel.sh cli server:list $TENANT_ID)
The link changes whenever the tunnel restarts. Stop: ./deploy/testing/quick-tunnel.sh down
EOF
}

case "${1:-}" in
  up) up ;;
  down) down ;;
  cli) shift; cli "$@" ;;
  *) sed -n '6,8p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 2 ;;
esac
